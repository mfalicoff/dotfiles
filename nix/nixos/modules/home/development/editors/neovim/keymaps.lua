-- LazyVim-style behavior using Nix-managed plugins and native Neovim APIs.
local function map(mode, lhs, rhs, desc)
  vim.keymap.set(mode, lhs, rhs, { silent = true, desc = desc })
end

local function root()
  local name = vim.api.nvim_buf_get_name(0)
  local start = name ~= "" and name or vim.fn.getcwd()
  return vim.fs.root(start, {
    ".git",
    "package.json",
    "pyproject.toml",
    "go.mod",
    "mix.exs",
    "build.zig",
    function(name)
      return name:match("%.sln$") ~= nil or name:match("%.csproj$") ~= nil
    end,
  }) or vim.fn.getcwd()
end

local function pick(source, cwd)
  return function()
    Snacks.picker[source]({ cwd = cwd == "root" and root() or nil })
  end
end

