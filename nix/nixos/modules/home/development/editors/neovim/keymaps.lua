local group = vim.api.nvim_create_augroup("NixvimBehavior", { clear = true })
vim.api.nvim_create_autocmd("TextYankPost", {
  group = group,
  callback = function()
    vim.hl.on_yank()
  end,
})
vim.api.nvim_create_autocmd("BufReadPost", {
  group = group,
  callback = function(event)
    local mark = vim.api.nvim_buf_get_mark(event.buf, '"')
    if
      mark[1] > 0
      and mark[1] <= vim.api.nvim_buf_line_count(event.buf)
      and vim.bo[event.buf].filetype ~= "gitcommit"
    then
      pcall(vim.api.nvim_win_set_cursor, 0, mark)
    end
  end,
})
